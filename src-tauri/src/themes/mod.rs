pub fn get_active_workspace_dir() -> PathBuf {
  let cfg_path = get_config_file_path();
  if let Ok(content) = fs::read_to_string(&cfg_path) {
    if let Ok(val) = serde_json::from_str::<Value>(&content) {
      if let Some(custom) = val.get("workspaceDir").and_then(|v| v.as_str()) {
        let p = PathBuf::from(custom);
        if p.is_dir() {
          return p;
        }
      }
    }
  }
  let default_p = get_default_workspace_dir();
  let _ = fs::create_dir_all(&default_p);
  default_p
}

pub fn validate_theme_id(id: &str) -> Result<String, String> {
  let trimmed = id.trim();
  if trimmed.is_empty() {
    return Err("Theme ID cannot be empty".to_string());
  }
  let mut comps = Path::new(trimmed).components();
  match (comps.next(), comps.next()) {
    (Some(Component::Normal(n)), None) => {
      let s = n.to_string_lossy().to_string();
      if s.starts_with('.') || s == ".trash" {
        return Err(format!("Theme ID cannot start with '.' or be named .trash: '{}'", trimmed));
      }
      if s.contains(['<', '>', ':', '"', '/', '\\', '|', '?', '*']) {
        return Err(format!("Theme ID contains illegal path characters: '{}'", trimmed));
      }
      Ok(s)
    }
    _ => Err(format!("Invalid theme ID path traversal: '{}'", trimmed)),
  }
}

fn sanitize_slug(name: &str) -> String {
  let clean: String = name
    .chars()
    .map(|c| if c.is_alphanumeric() || c == '-' || c == '_' { c } else { '-' })
    .collect();
  let trimmed = clean.trim_matches('-');
  if trimmed.is_empty() {
    "custom-theme".to_string()
  } else {
    trimmed.to_lowercase()
  }
}

fn validate_safe_rel_path(base: &Path, rel_path: &str) -> Result<PathBuf, String> {
  let normalized = rel_path.replace('\\', "/");
  let p = Path::new(&normalized);
  for comp in p.components() {
    match comp {
      Component::Normal(c) => {
        let name = c.to_string_lossy();
        if name.starts_with('.') || name.contains(".tmp_") {
          return Err(format!("Hidden/temp path components not allowed: '{}'", rel_path));
        }
      }
      _ => return Err(format!("Invalid path traversal component in '{}'", rel_path)),
    }
  }
  let full = base.join(p);
  Ok(full)
}

fn safe_write_file(target: &Path, content: &str) -> Result<(), String> {
  if let Some(parent) = target.parent() {
    let _ = fs::create_dir_all(parent);
  }
  let rand_id = SystemTime::now()
    .duration_since(UNIX_EPOCH)
    .map(|d| d.as_nanos())
    .unwrap_or(0);
  let tmp = target.with_extension(format!("tmp_{}", rand_id));
  if fs::write(&tmp, content).is_ok() {
    if fs::rename(&tmp, target).is_ok() {
      return Ok(());
    }
    let _ = fs::remove_file(&tmp);
  }
  fs::write(target, content).map_err(|e| format!("Failed to write file {}: {}", target.display(), e))
}

fn get_dir_stats(dir: &Path) -> (usize, u64) {
  let mut file_count = 0;
  let mut latest_mtime = 0;
  if let Ok(entries) = fs::read_dir(dir) {
    for entry in entries.flatten() {
      let path = entry.path();
      let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
      if name.starts_with('.') || name.contains(".tmp_") {
        continue;
      }
      if path.is_file() {
        file_count += 1;
        if let Ok(m) = fs::metadata(&path).and_then(|md| md.modified()) {
          let secs = m.duration_since(UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
          if secs > latest_mtime {
            latest_mtime = secs;
          }
        }
      } else if path.is_dir() {
        let (sub_count, sub_mtime) = get_dir_stats(&path);
        file_count += sub_count;
        if sub_mtime > latest_mtime {
          latest_mtime = sub_mtime;
        }
      }
    }
  }
  (file_count, latest_mtime)
}

pub fn init_theme_watcher(app_handle: AppHandle) -> Option<RecommendedWatcher> {
  let root = get_active_workspace_dir();
  let _ = fs::create_dir_all(&root);

  let app_clone = app_handle.clone();
  let root_captured = root.clone();

  let mut watcher = notify::recommended_watcher(move |res: notify::Result<Event>| {
    if let Ok(event) = res {
      match event.kind {
        EventKind::Create(_) | EventKind::Modify(_) | EventKind::Remove(_) => {
          for path in event.paths {
            if let Some(filename) = path.file_name().and_then(|n| n.to_str()) {
              if filename.contains(".tmp_") || filename.starts_with('.') {
                continue;
              }
            }
            if let Ok(rel) = path.strip_prefix(&root_captured) {
              let mut components = rel.components();
              if let Some(Component::Normal(theme_folder)) = components.next() {
                let theme_id = theme_folder.to_string_lossy().to_string();
                if theme_id == ".trash" || is_theme_internally_writing(&theme_id) {
                  continue;
                }
                let rel_file = components.as_path().to_string_lossy().to_string();
                let _ = app_clone.emit("theme-files-changed", FileChangeEventPayload {
                  theme_id,
                  path: rel_file,
                  kind: format!("{:?}", event.kind),
                });
              }
            }
          }
        }
        _ => {}
      }
    }
  }).ok()?;

  let _ = watcher.watch(&root, RecursiveMode::Recursive);
  Some(watcher)
}

