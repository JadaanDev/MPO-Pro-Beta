#[tauri::command]
pub fn delete_disk_theme(id: String) -> Result<(), String> {
  let safe_id = validate_theme_id(&id)?;
  let root = get_active_workspace_dir();
  let theme_dir = root.join(&safe_id);
  if !theme_dir.exists() {
    return Ok(());
  }
  let trash_dir = root.join(".trash");
  let _ = fs::create_dir_all(&trash_dir);
  let epoch_secs = SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
  let target_trash = trash_dir.join(format!("{}_{}", safe_id, epoch_secs));
  fs::rename(&theme_dir, &target_trash).map_err(|e| format!("Failed to move theme to trash: {}", e))?;
  Ok(())
}

